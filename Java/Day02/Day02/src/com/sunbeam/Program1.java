package com.sunbeam;

public class Program1 {
    public static void main(String[] args) {
    	for(int i = 1 ; i <= 20 ; i++) {
    		if(i % 2 == 0) {
    			System.out.println("Even Numbers : "+ i + " ");
    		}
    		else {
    			System.out.println("Odd Numbers : "+ i + " ");
    		}
    	}
    }
}
